async (page) => {
  const credentials = __TEST_CREDENTIALS__;
  const config = __TEST_CONFIG__;
  const base = config.base_url;
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const unexpected = [];
  const errors = [];
  page.on('request', request => { if (!request.url().startsWith(base)) unexpected.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/login/');
  await page.getByLabel('Username or email').fill('browser-user');
  await page.getByLabel('Password:', {exact: true}).fill(credentials.user_password);
  await page.getByRole('button', {name: 'Sign in', exact: true}).click();
  await page.waitForURL('**/password/');
  await page.getByLabel('Old password:', {exact: true}).fill(credentials.user_password);
  await page.getByLabel('New password:', {exact: true}).fill(credentials.changed_password);
  await page.getByLabel('New password confirmation:', {exact: true}).fill(credentials.changed_password);
  await page.getByRole('button', {name: 'Change password', exact: true}).click();
  check(await page.getByRole('link', {name: 'Accounts', exact: true}).count() === 0, 'USER sees admin link');
  const adminResponse = await page.request.get(base + '/admin/');
  check(adminResponse.status() === 403, 'USER can access admin');
  const exportResponse = await page.request.post(base + '/admin/export/', {form: {confirm: 'on'}});
  check(exportResponse.status() === 403, 'USER can export all mail');
  const rows = page.locator('.mail-row');
  check(await rows.count() === 2, 'Expected two delivered messages');
  await rows.filter({hasText: 'Browser MIME test'}).click();
  const messageUrl = page.url();
  check(await page.getByText('Browser plain text body', {exact: false}).count() > 0, 'Missing plain body');
  await page.getByRole('button', {name: 'Mark read', exact: true}).click();
  check(await page.getByRole('button', {name: 'Mark unread', exact: true}).count() === 1, 'Read state not persisted');
  check(unexpected.length === 0, 'Remote content loaded before consent');
  check(await page.locator('iframe').count() === 0, 'HTML loaded before consent');
  await page.route('https://tracker.invalid/**', route => route.fulfill({status: 204}));
  await page.getByRole('button', {name: 'Show full view', exact: true}).click();
  const frame = page.frameLocator('iframe[title="Email HTML"]');
  await frame.getByRole('heading', {name: 'Browser safe HTML'}).waitFor();
  check(await frame.locator('img').count() > 0, 'Email image removed');
  check(await frame.locator('a[href]').count() > 0, 'Email link removed');
  check(await page.evaluate(() => window.hacked) === undefined, 'Email script executed');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', {name: 'report.txt', exact: true}).click();
  const download = await downloadPromise;
  check(download.suggestedFilename() === 'report.txt', 'Unsafe attachment filename');
  await download.saveAs(config.artifacts_dir + '/browser-attachment.txt');
  await page.setViewportSize({width: 390, height: 844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
  await page.screenshot({path: config.artifacts_dir + '/browser-inbox-mobile.png', fullPage: true});
  await page.getByRole('link', {name: 'Delete', exact: true}).click();
  await page.getByLabel('I understand and confirm').check();
  await page.getByRole('button', {name: 'Delete permanently', exact: true}).click();
  check(await page.locator('.mail-row').count() === 1, 'Deletion failed');
  check((await page.request.get(messageUrl)).status() === 404, 'Deleted message still accessible');
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  await page.setViewportSize({width: 1280, height: 900});
  check(unexpected.every(url => url.startsWith('https://tracker.invalid/')), 'Unexpected external requests: ' + unexpected.join(','));
  check(errors.length === 0, 'Browser JavaScript errors: ' + errors.join(','));
  return {passed: ['forced password change', 'USER authorization', 'inbox delivery', 'read state', 'HTML isolation', 'opt-in remote resources', 'attachment download', 'mobile layout', 'message deletion'], deletedMessageUrl: messageUrl};
}
