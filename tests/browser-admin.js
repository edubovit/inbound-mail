async (page) => {
  const credentials = __TEST_CREDENTIALS__;
  const config = __TEST_CONFIG__;
  const base = config.base_url;
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto(base + '/login/');
  await page.getByLabel('Username or email').fill(credentials.admin);
  await page.getByLabel('Password:', {exact: true}).fill(credentials.admin_password);
  await page.getByRole('button', {name: 'Sign in', exact: true}).click();
  await page.getByRole('link', {name: 'Accounts', exact: true}).click();
  await page.getByRole('link', {name: 'browser-user@' + config.mail_domain, exact: true}).click();
  check(await page.getByLabel('Username:', {exact: true}).count() === 0, 'Username is editable');
  await page.getByRole('combobox', {name: 'Role:', exact: true}).click();
  await page.getByRole('option', {name: 'ADMIN', exact: true}).click();
  await page.getByLabel('Mailbox quota (MiB)').fill('128');
  await page.getByRole('button', {name: 'Save account', exact: true}).click();
  const row = page.locator('.account-row').filter({hasText: 'browser-user@' + config.mail_domain});
  check((await row.innerText()).includes('ADMIN'), 'Role edit failed');
  check((await row.innerText()).includes('128'), 'Quota edit failed');
  await page.getByRole('link', {name: 'browser-user@' + config.mail_domain, exact: true}).click();
  await page.getByRole('combobox', {name: 'Role:', exact: true}).click();
  await page.getByRole('option', {name: 'USER', exact: true}).click();
  await page.getByRole('button', {name: 'Save account', exact: true}).click();
  await page.getByRole('link', {name: 'Export all mail', exact: true}).click();
  await page.getByLabel('I understand and confirm').check();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download archive', exact: true}).click();
  const download = await downloadPromise;
  await download.saveAs(config.artifacts_dir + '/browser-export.tar');
  await page.getByRole('link', {name: 'Accounts', exact: true}).click();
  await page.getByRole('link', {name: 'browser-user@' + config.mail_domain, exact: true}).click();
  await page.getByRole('link', {name: 'Reset password', exact: true}).click();
  await page.getByLabel('Temporary password').fill(credentials.reset_password);
  await page.getByRole('button', {name: 'Reset password', exact: true}).click();
  check((await page.locator('.account-row').filter({hasText: 'browser-user@' + config.mail_domain}).innerText()).includes('Change required'), 'Reset not required');
  await page.getByRole('link', {name: 'browser-admin@' + config.mail_domain, exact: true}).click();
  await page.getByRole('link', {name: 'Delete account', exact: true}).click();
  await page.getByLabel('I understand and confirm').check();
  await page.getByRole('button', {name: 'Delete account permanently', exact: true}).click();
  check(await page.getByRole('link', {name: 'browser-admin@' + config.mail_domain, exact: true}).count() === 0, 'Account deletion failed');
  await page.getByRole('link', {name: credentials.admin + '@' + config.mail_domain, exact: true}).click();
  await page.getByRole('combobox', {name: 'Role:', exact: true}).click();
  await page.getByRole('option', {name: 'USER', exact: true}).click();
  await page.getByRole('button', {name: 'Save account', exact: true}).click();
  check(await page.getByText('Cannot demote the final administrator.', {exact: true}).count() === 1, 'Final admin protection absent');
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  return {passed: ['fixed addresses', 'role changes', 'quota editing', 'all-mail export', 'password reset', 'account purge', 'final-admin protection']};
}
