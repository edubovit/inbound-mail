async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const base = 'http://127.0.0.1:8000';
  await page.setViewportSize({width: 1280, height: 900});
  await page.goto(base + '/login/');
  check(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme) === 'dark', 'Login is not dark');
  await page.screenshot({path: '.local/dark-login.png', fullPage: true});
  await page.getByLabel('Username or email').fill('previewadmin');
  await page.getByLabel('Password:', {exact: true}).fill('Local-preview-only-248!');
  await page.getByRole('button', {name: 'Sign in', exact: true}).click();
  await page.getByRole('heading', {name: 'Inbox', exact: true}).waitFor();
  await page.locator('#inbox-status[data-state="live"]').waitFor();
  check(await page.locator('.mail-row').count() === 5, 'Unexpected preview fixture');
  check(await page.evaluate(() => getComputedStyle(document.body).backgroundColor) === 'rgb(11, 16, 23)', 'Inbox is not dark');
  await page.screenshot({path: '.local/dark-inbox-desktop.png', fullPage: true});
  await page.getByRole('link', {name: 'Accounts', exact: true}).click();
  await page.getByRole('heading', {name: 'Accounts', exact: true}).waitFor();
  await page.screenshot({path: '.local/dark-accounts.png', fullPage: true});
  await page.getByRole('link', {name: 'Inbox', exact: true}).click();
  await page.locator('.mail-row').filter({hasText: 'Notes from the infrastructure review'}).click();
  await page.getByText('Safe HTML view', {exact: true}).click();
  const frame = page.frameLocator('iframe[title="Email HTML"]');
  await frame.getByRole('heading', {name: 'Infrastructure review'}).waitFor();
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow !== null);
  const emailFrame = page.frames().find(candidate => candidate.url().includes('/html/'));
  await emailFrame.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(14, 21, 31)');
  check(await frame.locator('body script,body img,body style,body [href],body [src]').count() === 0, 'Unsafe email content survived');
  check(await page.evaluate(() => window.hacked) === undefined, 'Email script executed');
  await page.screenshot({path: '.local/dark-message-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Message mobile overflow');
  await page.screenshot({path: '.local/dark-message-mobile.png', fullPage: true});
  await page.getByRole('link', {name: 'Inbox', exact: true}).first().click();
  await page.getByRole('heading', {name: 'Inbox', exact: true}).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Inbox mobile overflow');
  await page.screenshot({path: '.local/dark-inbox-mobile.png', fullPage: true});
  await page.setViewportSize({width: 1280, height: 900});
  await page.evaluate(() => { window.__inboxVisit = 'initial-render'; });
  return {passed: ['dark login', 'dark inbox', 'dark accounts', 'dark isolated HTML', 'email sanitization', 'desktop/mobile layout'], readyForDelivery: true};
}
